"""generate_css.py — design-first sites: the public tokens.css and the matching trace map (plan 0.4 B.3.1, B.3.3).

Usage: generate_css.py --site <site design folder> [--tokens PATH] [--write]
Without --write it prints what it would write. Deterministic: the same DESIGN.md gives the same bytes, LF line ends on
every platform (what check_design.py regenerates and compares). Reads DESIGN.md, site.yaml, policy.yaml (its scheme
pairs) and the existing trace-map.yaml (clamp_expr); so the policy comes before the first generation.
Names: --color-<t>, --radius-<t>, --space-<t>, --type-<level>-family|size|weight|line|tracking,
--comp-<component>-<field>. With scheme both, a prefers-color-scheme: dark block from the policy's pairs.
Fluid sizes: the whole clamp() comes from trace-map.yaml (clamp_expr); DESIGN.md keeps the upper bound.
The tokens file must lie outside the site design folder and, when site.yaml names a deploy root, inside it; the trace
map is written into the site design folder (its own file). Every component field is bound to its variable again.
Outcomes: 0 printed or written, 2 an input or destination unusable (named), 4 unexpected."""
import argparse
import os
import sys
import traceback

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import csslite  # noqa: E402
import designlib as dl  # noqa: E402

VERSION = "0.1.0"
TYPO_VARS = (("fontFamily", "family"), ("fontSize", "size"), ("fontWeight", "weight"),
             ("lineHeight", "line"), ("letterSpacing", "tracking"))
COMP_VARS = {"backgroundColor": "bg", "textColor": "text", "rounded": "radius", "padding": "padding",
             "size": "size", "height": "height", "width": "width"}
PREFIX = {"colors": "--color-", "rounded": "--radius-", "spacing": "--space-"}
# The CSS property of a component field in a component stylesheet (plan 0.4 B.3.3 step 5, R2-M13); "size" has no single
# property and keeps its variable
COMP_PROPS = {"backgroundColor": ("background-color", "background"), "textColor": ("color",), "rounded": ("border-radius",),
              "padding": ("padding",), "height": ("height",), "width": ("width",)}
TYPO_CSS = ("font-family", "font-size", "font-weight", "line-height", "letter-spacing", "font")


def var_for_ref(ref):
    g, name = dl.REF.match(ref.strip()).groups()
    if g in PREFIX:
        return "var(%s%s)" % (PREFIX[g], name)
    raise dl.ContentError("reference %s cannot be a CSS variable" % ref)


def value_of(v):
    return var_for_ref(v) if dl.is_ref(v) else str(v)


def render(design, tmap, policy, design_sha):
    lines = ["/* generated by site-design-system generate_css.py %s, do not edit; source DESIGN.md sha256 %s */" % (VERSION, design_sha),
             ":root {"]
    for g in ("colors", "rounded", "spacing"):
        for name, v in design[g].items():
            lines.append("  %s%s: %s;" % (PREFIX[g], name, value_of(v)))
    for level, tok in design["typography"].items():
        clamp = ((tmap.get("typography") or {}).get(level) or {}).get("clamp_expr")
        for key, short in TYPO_VARS:
            if key in tok:
                v = clamp if key == "fontSize" and clamp else tok[key]
                if key == "fontFamily":
                    v = '"%s"' % v
                lines.append("  --type-%s-%s: %s;" % (level, short, v))
    for comp, fields in design["components"].items():
        for key, short in COMP_VARS.items():
            if key in fields:
                lines.append("  --comp-%s-%s: %s;" % (comp, short, value_of(fields[key])))
    lines.append("}")
    scheme = policy.get("scheme") or {}
    if scheme.get("mode") == "both":
        lines.append("@media (prefers-color-scheme: dark) {")
        lines.append("  :root {")
        for light, dark in sorted((scheme.get("pairs") or {}).items()):
            lines.append("    --color-%s: var(--color-%s);" % (light, dark))
        lines.append("  }")
        lines.append("}")
    return "\n".join(lines) + "\n"


def component_selector(comp, old_map):
    """A component's selector in its component stylesheets: the one the trace map already names for it (any field's
    sel), else .<component> (the convention; R2-M13)."""
    for b in ((old_map.get("components") or {}).get(comp) or {}).values() if isinstance((old_map.get("components") or {}).get(comp), dict) else []:
        if isinstance(b, dict) and b.get("sel"):
            return b["sel"][0] if isinstance(b["sel"], list) else b["sel"]
    return "." + comp


def render_map(design, old_map, comp_sheet=None):
    """The trace map of a design-first site. Component fields bind to their --comp-... variables until site.yaml names
    component stylesheets (comp_sheet, parsed); from then on every field those stylesheets define for the component's
    selector binds to that selector and property, and a field they do not define keeps its variable (B.3.3 step 5,
    R2-M13)."""
    """The trace map of a design-first site: every token bound to its generated variable."""
    out = {}
    for g in ("colors", "rounded", "spacing"):
        out[g] = {}
        for name, v in design[g].items():
            b = {"var": "%s%s" % (PREFIX[g], name)}
            if dl.is_ref(v):
                b["ref"] = v
            out[g][name] = b
    out["typography"] = {}
    for level, tok in design["typography"].items():
        b = {"vars": {key: "--type-%s-%s" % (level, short) for key, short in TYPO_VARS if key in tok}}
        clamp = ((old_map.get("typography") or {}).get(level) or {}).get("clamp_expr")
        if clamp:
            b["clamp_expr"] = clamp
        out["typography"][level] = b
    out["components"] = {}
    for comp, fields in design["components"].items():
        out["components"][comp] = {}
        sel = component_selector(comp, old_map)
        decls = (csslite.find(comp_sheet, sel) or {}) if comp_sheet is not None else {}
        for key, v in fields.items():
            if key == "typography":
                b = {"ref": v}
                if any(p in decls for p in TYPO_CSS):
                    b = {"sel": sel, "ref": v}
                out["components"][comp][key] = b
                continue
            prop = next((p for p in COMP_PROPS.get(key, ()) if p in decls), None)
            b = {"sel": sel, "prop": prop} if prop else {"var": "--comp-%s-%s" % (comp, COMP_VARS[key])}
            if dl.is_ref(v):
                b["ref"] = v
            out["components"][comp][key] = b
    return out


def inside(path, folder):
    try:
        return os.path.commonpath([os.path.realpath(path), os.path.realpath(folder)]) == os.path.realpath(folder)
    except ValueError:            # another drive
        return False


def destination_problem(tokens, site_dir, site):
    """None, or why the public tokens file must not be written there (AST-M04): never inside the site design folder,
    and inside the deploy root when site.yaml names one."""
    if inside(tokens, site_dir):
        return "the tokens file %s lies inside the site design folder (it is public: it belongs under the deploy root)" % tokens
    root = site.get("deploy_root")
    if root:
        root = root if os.path.isabs(root) else os.path.join(site_dir, root)
        if not inside(tokens, root):
            return "the tokens file %s lies outside the deploy root %s" % (tokens, os.path.realpath(root))
    return None


def write_lf(path, text):
    """Write text with LF line ends on every platform: the bytes check_design.py regenerates (AST-M05), through the
    shared safe writer: never through an existing link or hard link (R2-M03)."""
    dl.write_output(path, text.replace("\r\n", "\n").encode("utf-8"))


def component_sheet(site_dir, site, snap):
    """The component stylesheets site.yaml names, parsed into one sheet; None when it names none (R2-M13)."""
    paths = site.get("component_stylesheets") or []
    paths = paths if isinstance(paths, list) else [paths]
    if not paths:
        return None
    merged = csslite.Sheet()
    for p in paths:
        full = p if os.path.isabs(p) else os.path.normpath(os.path.join(site_dir, p))
        try:
            merged.rules += csslite.parse(snap.text(full)).rules
        except ValueError as exc:
            raise dl.ContentError("the component stylesheet %s cannot be read: %s" % (p, exc))
    return merged


def run(a):
    snap = dl.Snapshot()
    site_dir = os.path.realpath(a.site)
    dl.require_yaml()
    fm, _ = dl.split_front_matter(snap.text(os.path.join(site_dir, "DESIGN.md")))
    design = dl.load_yaml_text(fm, "DESIGN.md front matter")
    site = dl.load_yaml_text(snap.text(os.path.join(site_dir, "site.yaml")), "site.yaml")
    policy = dl.load_yaml_text(snap.text(os.path.join(site_dir, "policy.yaml")), "policy.yaml")
    map_path = os.path.join(site_dir, "trace-map.yaml")
    why = dl.output_name_problem(map_path)        # read and written through the same validated name (R2-M03)
    if why:
        raise dl.InputError(why)
    old = dl.load_yaml_text(snap.text(map_path), "trace-map.yaml") if os.path.exists(map_path) else {}
    for g in ("colors", "rounded", "spacing", "typography", "components"):
        if not isinstance(design.get(g), dict):
            raise dl.ContentError("DESIGN.md group %s is missing or not a mapping" % g)
    try:
        css = render(design, old, policy, snap.digest(os.path.join(site_dir, "DESIGN.md")))
        comp_sheet = component_sheet(site_dir, site, snap)
        tmap_data = render_map(design, old, comp_sheet)
    except (KeyError, AttributeError, TypeError) as exc:
        raise dl.ContentError("DESIGN.md cannot be rendered: %s %s" % (type(exc).__name__, exc))
    import yaml
    tmap = yaml.safe_dump(tmap_data, sort_keys=False, allow_unicode=True)
    tokens = a.tokens or os.path.join(site_dir, site.get("public_tokens", "tokens.css"))
    if a.write:
        why = destination_problem(tokens, site_dir, site)
        if why:
            raise dl.InputError(why)
        try:
            write_lf(tokens, css)
            write_lf(map_path, tmap)
        except OSError as exc:
            raise dl.InputError("cannot write: %s" % (exc.strerror or exc))
        print("generate_css: wrote %s and %s" % (tokens, map_path))
    else:
        print(css)
        print(tmap)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--site", required=True)
    ap.add_argument("--tokens")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    try:
        return run(a)
    except (dl.InputError, dl.ContentError) as exc:   # inside the handler: ERROR 2 (AUD-F11)
        print("generate_css: ERROR %s" % exc)
        return 2
    except Exception as exc:  # noqa: BLE001
        traceback.print_exc()
        print("generate_css: INTERNAL (%s)" % exc)
        return 4


if __name__ == "__main__":
    sys.exit(main())
