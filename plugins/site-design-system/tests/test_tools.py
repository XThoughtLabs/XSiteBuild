"""Tests of inventory_css.py and generate_css.py (plan 0.4 B.3), and of the mutation runner's output handling (X4)."""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
sys.path.insert(0, HERE)
import sites  # noqa: E402

sys.path.insert(0, sites.SCRIPTS)
import inventory_css  # noqa: E402


def test_inventory_of_x(tmp_path):
    d = sites.build_x(tmp_path)
    css = os.path.join(os.path.dirname(d), "site", "x.css")
    inv = inventory_css.inventory([css])
    assert "--ink" in {c["name"] for c in inv["custom_properties"]} and len(inv["font_faces"]) == 1
    assert [k["name"] for k in inv["keyframes"]] == ["pulse"]
    assert not inv["unsupported"]
    out = tmp_path / "inv.json"
    r = subprocess.run([sys.executable, "-I", "-B", os.path.join(sites.SCRIPTS, "inventory_css.py"), css, "--json", str(out)],
                       capture_output=True, text=True)
    assert r.returncode == 0 and json.loads(out.read_text()) == json.loads(json.dumps(inv))


def test_inventory_unsupported_exit_3(tmp_path):
    css = tmp_path / "s.css"
    css.write_text("@layer base { a { color: red; } }\n")
    r = subprocess.run([sys.executable, "-I", "-B", os.path.join(sites.SCRIPTS, "inventory_css.py"), str(css)], capture_output=True, text=True)
    assert r.returncode == 3 and "@layer" in r.stdout


def test_inventory_lists_longhands(tmp_path):
    """AST-L02: the common longhands are inventoried (the claim is the list of PROPS)."""
    css = tmp_path / "l.css"
    css.write_text(".a { border-top-color: #123456; padding-left: 4px; text-shadow: 0 1px red; }\n")
    props = {v["property"] for v in inventory_css.inventory([str(css)])["values"]}
    assert {"border-top-color", "padding-left", "text-shadow"} <= props, props


def test_generate_is_deterministic_and_write_matches(tmp_path):
    d = sites.build_y(tmp_path)
    gen = os.path.join(sites.SCRIPTS, "generate_css.py")
    a = subprocess.run([sys.executable, "-I", "-B", gen, "--site", d], capture_output=True, text=True).stdout
    b = subprocess.run([sys.executable, "-I", "-B", gen, "--site", d], capture_output=True, text=True).stdout
    assert a == b and a.startswith("/* generated by site-design-system")
    tokens = open(os.path.join(os.path.dirname(d), "site", "tokens.css")).read()
    assert a.startswith(tokens)


def test_mutation_runner_reads_any_output_of_a_killer(tmp_path):
    """X4 (CC-06's Question 6): a killer whose output holds non-ASCII text (Cyrillic in its docstring and message) and
    bytes that are no text in any encoding never crashes run_mutants.py, in any code page: the child writes UTF-8 and the
    runner reads it as UTF-8 with replacement, so the failing killer is still named. The killer is a real pytest child
    in its own folder; capsys.disabled() writes its raw bytes past pytest's capture, onto the runner's pipe."""
    sys.path.insert(0, os.path.join(HERE, "mutation"))
    import run_mutants
    cyr = "Проверка"            # a Cyrillic word, written into the killer only
    (tmp_path / "test_k.py").write_text(
        "import sys\n\n\ndef test_k(capsys):\n"
        "    \"\"\"%s: a docstring in another script.\"\"\"\n"
        "    with capsys.disabled():\n"
        "        sys.stdout.buffer.write('%s '.encode('utf-8') + b'\\x90\\x81\\xff\\n')\n"
        "        sys.stdout.flush()\n"
        "    assert False, '%s'\n" % (cyr, cyr, cyr), encoding="utf-8")
    assert run_mutants.pytest(str(tmp_path), ["test_k.py::test_k"]) == ("FAILED", "killed by test_k.py::test_k")
    (tmp_path / "test_k.py").write_text("def test_k():\n    pass\n", encoding="utf-8")         # control: a passing killer
    assert run_mutants.pytest(str(tmp_path), ["test_k.py::test_k"])[0] == "PASSED"
